import type { DiagnosticArgs } from "./diagnostic.js";
import type { MessageEntry, MessageTable } from "./messages-en.js";

/** Reads one detail; missing details become empty text so a message never shows "undefined". */
const arg = (args: DiagnosticArgs, key: string): string => args[key] ?? "";

/** The message for a robot part that does not exist: E203 (frame), E204 (actuator), E205 (sensor). */
function partMessage(part: string): MessageEntry {
  return {
    message: (a) => `रोबोट '${arg(a, "robot")}' में '${arg(a, "name")}' नाम का ${part} नहीं है`,
    fix: (a) =>
      arg(a, "suggestion") !== ""
        ? `क्या आपका मतलब '${arg(a, "suggestion")}' था?`
        : arg(a, "known") !== ""
          ? `इसके ${part} ये हैं: ${arg(a, "known")}।`
          : `इस रोबोट में कोई ${part} नहीं है।`,
  };
}

